func TestGenerateRejects(t *testing.T) {
	hostileNames := []string{
		"", "UPPER", "a b", "a;b", "a'b", `a"b`, "a$b", "a`b", "$(id)", "../x", "a/b", `a\b`, "-lead", "a\nb", "a\x00b",
		"x" + strings.Repeat("a", 63), "é", "a.b", "a_b",
	}
	for _, n := range hostileNames {
		for _, sh := range Shells() {
			goos := "linux"
			if sh == Cmd {
				goos = "windows"
			}
			if out, err := Generate(sh, goos, []string{"ok", n}, "/bin/ccshelf"); err == nil || out != "" {
				if sh == Cmd {
					if _, err = Generate(sh, goos, []string{n}, winExe); err == nil {
						t.Errorf("%s accepted profile %q", sh, n)
					}
					continue
				}
				t.Errorf("%s accepted profile %q", sh, n)
			}
		}
	}
	badExe := []struct{ shell, goos, exe string }{
		{Bash, "linux", ""},
		{Bash, "linux", "ccshelf"},
		{Bash, "linux", "./ccshelf"},
		{Bash, "linux", "/bin/cc\nshelf"},
		{Bash, "linux", "/bin/cc\x1bshelf"},
		{Bash, "linux", "/bin/\xff"},
		{Bash, "linux", "/bin/\u202Eshelf"},
		{Pwsh, "windows", "ccshelf.exe"},
		{Pwsh, "windows", `C:rel\x`},
		{Pwsh, "windows", `\\`},
		{Cmd, "windows", `C:\a"b\x.exe`},
		{Cmd, "windows", `C:\100%\x.exe`},
		{Cmd, "windows", `C:\a$b\x.exe`},
		{Cmd, "linux", "/bin/ccshelf"},
		{"tcsh", "linux", "/bin/ccshelf"},
	}
	for _, tt := range badExe {
		if _, err := Generate(tt.shell, tt.goos, []string{"a"}, tt.exe); err == nil {
			t.Errorf("Generate(%s, %s, %q) accepted", tt.shell, tt.goos, tt.exe)
		}
	}
	for _, exe := range []string{`D:/tools/ccshelf.exe`, `\\server\share\ccshelf.exe`} {
		if _, err := Generate(Pwsh, "windows", []string{"a"}, exe); err != nil {
			t.Errorf("windows path %q rejected: %v", exe, err)
		}
	}
}

