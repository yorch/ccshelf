const (
	posixExe = "/opt/cc shelf/ccshelf"
	winExe   = `C:\Program Files\ccshelf\ccshelf.exe`
)

func golden(t *testing.T, name, got string) {
	t.Helper()
	path := filepath.Join("testdata", name)
	if os.Getenv("UPDATE_GOLDEN") != "" {
		if err := os.WriteFile(path, []byte(got), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if norm(got) != norm(string(want)) {
		t.Errorf("%s mismatch\n--- got ---\n%s\n--- want ---\n%s", name, got, want)
	}
}

func TestGenerateGolden(t *testing.T) {
	profiles := []string{"sre", "frontend", "seo-2", "sre"}
	tests := []struct {
		shell, goos, exe, file string
	}{
		{Bash, "linux", posixExe, "bash.golden"},
		{Zsh, "darwin", posixExe, "zsh.golden"},
		{Fish, "linux", "/opt/it's/ccshelf", "fish.golden"},
		{Pwsh, "windows", winExe, "pwsh.golden"},
		{Pwsh, "linux", "/opt/it's/ccshelf", "pwsh_posix.golden"},
		{Cmd, "windows", winExe, "cmd.golden"},
	}
	for _, tt := range tests {
		t.Run(tt.file, func(t *testing.T) {
			got, err := Generate(tt.shell, tt.goos, profiles, tt.exe)
			if err != nil {
				t.Fatal(err)
			}
			golden(t, tt.file, got)
		})
	}
}

